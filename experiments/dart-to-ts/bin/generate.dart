/// Usage (from experiments/dart-to-ts):
///   dart run bin/generate.dart [widgetsDir] [registrationFile] [outFile]
///
/// Defaults point at packages/solid-fuse/dart and write out/widgets.generated.d.ts.
import 'dart:convert';
import 'dart:io';

import 'package:dart_to_ts/scrape.dart';
import 'package:path/path.dart' as p;

void main(List<String> args) {
  final repo = p.normalize(p.join(p.dirname(Platform.script.toFilePath()), '../../..'));
  final dartLib = p.join(repo, 'packages/solid-fuse/dart/lib/src');
  final widgetsDir = args.isNotEmpty ? args[0] : p.join(dartLib, 'widgets');
  final regFile = args.length > 1 ? args[1] : p.join(dartLib, 'solid_fuse_package.dart');
  final outFile = args.length > 2 ? args[2] : 'out/widgets.generated.d.ts';

  final files = Directory(widgetsDir)
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => f.path.endsWith('.dart'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final tags = scrapeRegistrations(File(regFile));
  final widgets = scrapeWidgets(files);
  for (final w in widgets) {
    w.tag = tags[w.className];
  }

  final buf = StringBuffer()
    ..writeln('// GENERATED by experiments/dart-to-ts. Do not edit.')
    ..writeln('import type * as T from "../../../packages/solid-fuse/src/types";')
    ..writeln('type ColorInput = T.ColorInput; type EdgeInsetsInput = T.EdgeInsetsInput;')
    ..writeln('type BorderRadiusInput = T.BorderRadiusInput; type BorderInput = T.BorderInput;')
    ..writeln('type ShadowInput = T.ShadowInput; type FontWeight = T.FontWeight;')
    ..writeln('type AlignmentString = T.AlignmentString;')
    ..writeln('// Not (yet) in types.ts — placeholders so the output type-checks:')
    ..writeln('type GradientInput = unknown; type DecorationImageInput = unknown;')
    ..writeln('type BoxDecorationInput = unknown; type BlendModeString = string; type ClipString = string;')
    ..writeln();

  final report = <Map<String, Object?>>[];
  for (final w in widgets) {
    final name = '${w.className.replaceFirst(RegExp(r'^Fuse'), '')}GeneratedProps';
    buf.writeln('/** ${w.className} (${p.relative(w.file, from: repo)})'
        '${w.tag != null ? ' — <${w.tag}>' : ''} */');
    buf.writeln('export interface $name {');
    for (final prop in w.props.values) {
      buf.writeln('  ${prop.name}?: ${prop.tsType};');
    }
    if (w.dynamicKeys.isNotEmpty) {
      buf.writeln('  // ${w.dynamicKeys.length} prop read(s) with non-literal keys not captured');
    }
    buf.writeln('}');
    buf.writeln();
    report.add({
      'class': w.className,
      'tag': w.tag,
      'interface': name,
      'props': {for (final pr in w.props.values) pr.name: pr.tsType},
      'dynamicKeys': w.dynamicKeys,
    });
  }

  File(outFile)
    ..createSync(recursive: true)
    ..writeAsStringSync(buf.toString());
  File(outFile.replaceFirst(RegExp(r'\.d\.ts$'), '.json'))
      .writeAsStringSync(const JsonEncoder.withIndent('  ').convert(report));
  stdout.writeln('Wrote $outFile (${widgets.length} widget classes)');
}
