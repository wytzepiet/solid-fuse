// Scrapes Flutter's framework sources for concrete public Widget subclasses with
// an unnamed constructor and emits Dart files that reference them through a
// `Map<String, Function>` of constructor tear-offs -- the minimal thing any
// "generated table of every widget" must contain, so it lower-bounds the
// tree-shaking cost of options A (kitchen-sink) and E (constructor interpreter).
//
// usage: node tool/gen_tables.mjs /opt/flutter [excludeFile]
import { readdirSync, readFileSync, writeFileSync, existsSync } from "fs";
import { join } from "path";

const flutterRoot = process.argv[2] ?? "/opt/flutter";
const excludeFile = process.argv[3];
const exclude = new Set(
  excludeFile && existsSync(excludeFile)
    ? readFileSync(excludeFile, "utf8").split("\n").filter(Boolean)
    : [],
);
const src = join(flutterRoot, "packages/flutter/lib/src");
const libs = ["widgets", "material", "cupertino"];

const superOf = new Map(); // class -> superclass
const info = new Map(); // class -> { lib, concrete, hasCtor }
for (const lib of libs) {
  for (const f of readdirSync(join(src, lib))) {
    if (!f.endsWith(".dart")) continue;
    const text = readFileSync(join(src, lib, f), "utf8");
    const re = /^((?:abstract |base |final |sealed |interface |mixin )*)class (\w+)(?:<[^{]*?>)? extends (\w+)/gm;
    let m;
    while ((m = re.exec(text))) {
      const [, mods, name, sup] = m;
      superOf.set(name, sup);
      const ctor = new RegExp(`^  (?:const )?${name}\\(`, "m").test(text);
      info.set(name, {
        lib,
        concrete: !/abstract|sealed|mixin/.test(mods) && !name.startsWith("_"),
        hasCtor: ctor,
      });
    }
  }
}
const isWidget = (n) => {
  for (let i = 0; i < 30 && n; i++) {
    if (n === "Widget") return true;
    n = superOf.get(n);
  }
  return false;
};
const byLib = { widgets: [], material: [], cupertino: [] };
for (const [name, i] of info) {
  if (i.concrete && i.hasCtor && isWidget(name) && !exclude.has(name)) byLib[i.lib].push(name);
}
for (const l of libs) byLib[l].sort();

const common = [
  "Align","AnimatedContainer","AnimatedOpacity","AppBar","AspectRatio","BottomNavigationBar","Card","Center",
  "Checkbox","Chip","CircularProgressIndicator","ClipRRect","Column","ConstrainedBox","Container","CustomScrollView",
  "DecoratedBox","Divider","Drawer","DropdownButton","ElevatedButton","Expanded","FilledButton","Flexible",
  "FloatingActionButton","GestureDetector","GridView","Icon","IconButton","Image","InkWell","LinearProgressIndicator",
  "ListTile","ListView","Opacity","OutlinedButton","Padding","PageView","Positioned","Radio","RefreshIndicator","Row",
  "SafeArea","Scaffold","SingleChildScrollView","SizedBox","Slider","SliverAppBar","SliverList","Spacer","Stack",
  "Switch","TabBar","TabBarView","Text","TextButton","TextField","Tooltip","Transform","Wrap",
];

function emit(file, imports, names) {
  const lines = [
    "// GENERATED by tool/gen_tables.mjs -- do not edit.",
    "// ignore_for_file: type=lint",
    ...imports.map((i) => `import '${i}';`),
    "",
    "@pragma('vm:entry-point')",
    "final Map<String, Function> table = <String, Function>{",
    ...names.map((n) => `  '${n}': ${n}.new,`),
    "};",
    "",
    "void main() {",
    "  // Looked up by a runtime string so nothing can be constant-folded away.",
    "  final f = table[String.fromEnvironment('W', defaultValue: 'Text')];",
    "  runApp(MaterialApp(home: Scaffold(body: Center(child: Text('${f.runtimeType} ${table.length}')))));",
    "}",
  ];
  writeFileSync(file, lines.join("\n") + "\n");
  console.log(file, names.length);
}

const M = "package:flutter/material.dart";
const C = "package:flutter/cupertino.dart";
emit("lib/main_common60.dart", [M], common);
emit("lib/main_widgets.dart", [M], byLib.widgets);
emit("lib/main_widgets_material.dart", [M], [...byLib.widgets, ...byLib.material]);
emit("lib/main_all.dart", [C, M], [...byLib.widgets, ...byLib.material, ...byLib.cupertino]);
