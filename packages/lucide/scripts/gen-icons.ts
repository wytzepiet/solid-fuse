#!/usr/bin/env bun
// Generates src/index.ts by parsing flutter_lucide's own icon source file.
// Each Lucide glyph becomes a tree-shakeable IconData export, mirroring how
// solid-fuse generates its Material and Cupertino icon sets.
//
// Run when the flutter_lucide dependency is bumped.
//
// Usage: bun scripts/gen-icons.ts [path/to/flutter_lucide.dart]
//
// With no argument it resolves the newest flutter_lucide-* in the pub cache.

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "fs";
import { resolve } from "path";

// Words reserved in JS/TS that can't be binding names.
// Source: ECMAScript strict-mode reserved words + some future-reserved.
const RESERVED = new Set([
  "break", "case", "catch", "class", "const", "continue", "debugger",
  "default", "delete", "do", "else", "enum", "export", "extends", "false",
  "finally", "for", "function", "if", "import", "in", "instanceof", "new",
  "null", "return", "super", "switch", "this", "throw", "true", "try",
  "typeof", "var", "void", "while", "with", "yield", "let", "static",
  "implements", "interface", "package", "private", "protected", "public",
  "await",
]);

function snakeToCamel(name: string): string {
  return name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function safeIdentifier(snake: string): string {
  let id = snakeToCamel(snake);
  if (/^\d/.test(id)) id = "_" + id;
  if (RESERVED.has(id)) id = id + "_";
  return id;
}

interface IconEntry {
  name: string;
  codePoint: number;
}

// Parses lines like:
//   static const IconData a_arrow_down = IconData(0xe585, fontFamily: _fontFamily, fontPackage: _fontPackage);
function parseIcons(source: string): IconEntry[] {
  const pattern =
    /static\s+const\s+IconData\s+(\w+)\s*=\s*IconData\s*\(\s*(0x[0-9a-fA-F]+)/g;
  const out: IconEntry[] = [];
  for (const m of source.matchAll(pattern)) {
    out.push({ name: m[1], codePoint: parseInt(m[2], 16) });
  }
  return out;
}

function emitModule(entries: IconEntry[], version: string): string {
  // Deduplicate by safe identifier, keeping the first occurrence.
  const seen = new Set<string>();
  const rows: { id: string; entry: IconEntry }[] = [];
  for (const entry of entries) {
    const id = safeIdentifier(entry.name);
    if (seen.has(id)) continue;
    seen.add(id);
    rows.push({ id, entry });
  }
  rows.sort((a, b) => a.id.localeCompare(b.id));

  const header = [
    "// @generated by scripts/gen-icons.ts from flutter_lucide.",
    `// Source: flutter_lucide@${version} (lib/src/flutter_lucide.dart)`,
    "// Do not edit by hand — re-run the script to regenerate.",
    "",
    'import type { IconData } from "solid-fuse";',
    "",
  ].join("\n");

  const factoryDef = [
    "const make = (codePoint: number): IconData => ({",
    "  codePoint,",
    '  fontFamily: "lucide",',
    '  fontPackage: "flutter_lucide",',
    "});",
  ].join("\n");

  const lines = rows.map(
    ({ id, entry }) =>
      `export const ${id} = /*#__PURE__*/ make(0x${entry.codePoint.toString(16)});`,
  );

  return [header, factoryDef, "", ...lines, ""].join("\n");
}

function resolvePubCacheSource(): { path: string; version: string } {
  const root = `${process.env.HOME}/.pub-cache/hosted/pub.dev`;
  const dirs = readdirSync(root)
    .filter((d) => d.startsWith("flutter_lucide-"))
    .sort();
  if (dirs.length === 0) {
    throw new Error(
      "No flutter_lucide in pub cache. Run `flutter pub get` in dart/, " +
        "or pass the path to lib/src/flutter_lucide.dart as an argument.",
    );
  }
  const dir = dirs[dirs.length - 1];
  return {
    path: `${root}/${dir}/lib/src/flutter_lucide.dart`,
    version: dir.replace("flutter_lucide-", ""),
  };
}

function main() {
  const arg = process.argv[2];
  const { path, version } = arg
    ? { path: arg, version: "local" }
    : resolvePubCacheSource();

  const source = readFileSync(path, "utf-8");
  const entries = parseIcons(source);

  const outDir = resolve(__dirname, "../src");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(`${outDir}/index.ts`, emitModule(entries, version));
  console.log(`Wrote ${entries.length} Lucide icons to src/index.ts`);
}

main();
