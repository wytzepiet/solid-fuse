import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { join, relative } from "path";
import { execSync } from "child_process";
import { defineCommand } from "citty";
import {
  findProjectRoot,
  getDartRoot,
  scanFusePackages,
  pubspecHasDependency,
  pubspecAddDependency,
  pubspecGetManagedDependencies,
  pubspecRemoveDependency,
  pubspecDependencies,
  type FusePackageInfo,
} from "./utils";
import { loadFuseConfig } from "./config";
import { GENERATED_DART, genOutDir, hasBarrels, runGen } from "./gen/command";
import { writeRoutes } from "./routes";

/**
 * Core link logic — exported so other commands (dev, build, install, remove) can call it.
 */
export async function runLink(projectRoot?: string, { pubGet = true, gen = true } = {}) {
  const root = projectRoot ?? findProjectRoot();
  console.log(`Project root: ${root}`);

  const fuseConfig = await loadFuseConfig(root);
  const dartRoot = getDartRoot(root, fuseConfig);

  const packages = await scanFusePackages(root);
  console.log(`Found ${packages.length} Fuse package(s):`);
  for (const pkg of packages) {
    console.log(`  - ${pkg.npmName} (${pkg.dartName})${pkg.registerClass ? ` → ${pkg.registerClass}` : ""}`);
  }

  const pubspecPath = join(dartRoot, "pubspec.yaml");
  const activeDartNames = new Set(packages.map((p) => p.dartName));

  // Add missing fuse packages to pubspec.yaml dependencies
  let changed = false;
  for (const pkg of packages) {
    if (!pubspecHasDependency(pubspecPath, pkg.dartName)) {
      pubspecAddDependency(pubspecPath, pkg.dartName);
      changed = true;
      console.log(`  Added ${pkg.dartName} to pubspec.yaml dependencies`);
    }
  }

  // Remove stale fuse-managed dependencies no longer in node_modules
  for (const managed of pubspecGetManagedDependencies(pubspecPath)) {
    if (!activeDartNames.has(managed)) {
      pubspecRemoveDependency(pubspecPath, managed);
      changed = true;
      console.log(`  Removed stale ${managed} from pubspec.yaml dependencies`);
    }
  }

  generatePubspecOverrides(dartRoot, packages);
  // A package added or removed needs pub get even where the caller leaves it
  // to Flutter: generation reads the resolved packages before Flutter runs.
  if (pubGet || changed) runFlutterPubGet(dartRoot);

  // Generated components and adapters (dart/lib/fuse.dart and every
  // resolved package's). After pub get, so a package just added is seen.
  // `fuse dev` and `fuse build` leave it to their Vite plugin (cli/gen/plugin.ts).
  if (gen && hasBarrels(dartRoot)) {
    try {
      const t0 = performance.now();
      const r = await runGen(root, fuseConfig);
      console.log(`fuse gen: ${r.manifest.widgets.length} widgets, ${r.manifest.handles.length} handles (${Math.round(performance.now() - t0)} ms)`);
    } catch (err) {
      // The previous output stays; the app still builds with it.
      console.error(`fuse gen failed: ${err instanceof Error ? err.message : err}`);
    }
  }

  // File routes (`#fuse/routes`), so the editor finds them before `fuse dev`.
  if (gen) {
    try {
      writeRoutes(root, join(root, genOutDir(fuseConfig)));
    } catch (err) {
      console.error(err instanceof Error ? err.message : err);
    }
  }

  generateFusePackagesDart(dartRoot, packages);

  const hidden = unexposedDependencies(dartRoot, packages);
  if (hidden.length > 0) {
    console.log(
      `\nNot exposed to JS: ${hidden.join(", ")}. To use one from TS, export it in dart/lib/fuse.dart:\n` +
        `  export 'package:${hidden[0]}/${hidden[0]}.dart';`,
    );
  }

  console.log("\nDone!");
}

/**
 * The app's own pub dependencies that its `dart/lib/fuse.dart` doesn't
 * mention: what crosses to JS is what that file exports, so a package added
 * with `flutter pub add` stays Dart-only until it does.
 */
export function unexposedDependencies(dartRoot: string, packages: FusePackageInfo[]): string[] {
  const pubspec = join(dartRoot, "pubspec.yaml");
  if (!existsSync(pubspec)) return [];
  const barrel = join(dartRoot, "lib", "fuse.dart");
  const exported = existsSync(barrel) ? readFileSync(barrel, "utf-8") : "";
  const fuse = new Set(packages.map((p) => p.dartName));
  return pubspecDependencies(pubspec).filter((name) => !fuse.has(name) && !exported.includes(`package:${name}/`));
}

export const linkCommand = defineCommand({
  meta: {
    name: "link",
    description: "Scan node_modules for Fuse packages and generate Dart glue code",
  },
  run: async () => {
    await runLink();
  },
});

function generatePubspecOverrides(
  dartRoot: string,
  packages: FusePackageInfo[]
) {
  const lines = ["# Generated by fuse link. Do not edit.", "dependency_overrides:"];

  for (const pkg of packages) {
    const relPath = relative(dartRoot, join(pkg.path, pkg.dartPath)).replace(
      /\\/g,
      "/"
    );
    lines.push(`  ${pkg.dartName}:`);
    lines.push(`    path: ${relPath}`);
  }

  const outPath = join(dartRoot, "pubspec_overrides.yaml");
  writeFileSync(outPath, lines.join("\n") + "\n");
  console.log(`\nWrote ${outPath}`);
}

function generateFusePackagesDart(
  dartRoot: string,
  packages: FusePackageInfo[]
) {
  const dir = join(dartRoot, "lib", "_generated");
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }

  const lines = ["// Generated by fuse link. Do not edit."];

  // Import FuseRuntime type only (no collision with register functions)
  lines.push("import 'package:solid_fuse/solid_fuse.dart' show FuseRuntime;");

  // Aliased imports for all packages
  // Packages whose Dart is all generated have nothing to register.
  const registering = packages.filter((pkg) => pkg.registerClass);
  for (const pkg of registering) {
    const alias = dartAlias(pkg.dartName);
    lines.push(`import 'package:${pkg.dartName}/${pkg.dartName}.dart' as ${alias};`);
  }

  // `fuse gen` output, when there is some.
  // The Vite plugin writes it in `fuse dev` / `fuse build`, after this.
  const generated = existsSync(join(dartRoot, GENERATED_DART)) || hasBarrels(dartRoot);
  if (generated) lines.push("import 'fuse.generated.dart' as fuse_generated;");

  lines.push("");
  lines.push("void registerFusePackages(FuseRuntime runtime) {");

  for (const pkg of registering) {
    const alias = dartAlias(pkg.dartName);
    lines.push(`  ${alias}.${pkg.registerClass}(runtime);`);
  }
  if (generated) lines.push("  fuse_generated.registerFuseGenerated(runtime);");

  lines.push("}");

  const outPath = join(dir, "fuse_packages.dart");
  writeFileSync(outPath, lines.join("\n") + "\n");
  console.log(`Wrote ${outPath}`);
}

/**
 * Convert a Dart package name to a safe import alias.
 * e.g. "solid_fuse" → "solid_fuse", "fuse_auth" → "fuse_auth"
 */
function dartAlias(dartName: string): string {
  return dartName.replace(/-/g, "_");
}

function runFlutterPubGet(dartRoot: string) {
  console.log("\nRunning flutter pub get...");
  try {
    execSync("flutter pub get", {
      cwd: dartRoot,
      stdio: "inherit",
    });
  } catch {
    throw new Error("flutter pub get failed");
  }
}
