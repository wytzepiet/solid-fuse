/**
 * File routes: every file in `src/app/` becomes a `route()`, written to
 * `<gen>/routes.tsx` (imported as `#fuse/routes`). Only codegen: what the
 * files say is what a hand-written `route()` would say.
 *
 * - A file is a page; its path is its address. `index` takes its folder's
 *   address, `[id]` is a param, `(group)` folders stay out of the address.
 *   Names starting with `_` aren't pages, for components and helpers.
 * - `x.tsx` next to an `x/` folder with an `index.tsx` holds that folder: the
 *   two share the address `/x`, and the folder's pages open in the stacks
 *   `x.tsx` draws (`in: x`). Without an index, `x/`'s pages open where `x` does.
 *   `src/app.tsx` holds `src/app/` the same way: the app's own stack.
 * - `name@x.tsx` opens in the stacks `x.tsx` holds instead; `@app` is the
 *   app's own stack. The `@` part isn't in the address.
 * - A file can `export const page` (its page type) and `export const parse`
 *   (its params from an address), as `route()` takes them.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync } from "fs";
import { dirname, join, relative } from "path";
import type { Plugin } from "vite";

export const ROUTES_HEADER = "// GENERATED by fuse from src/app/ (file routes). Do not edit.";

export type FileRoute = {
  /** The file, relative to the app folder: `users/[id].tsx`. */
  file: string;
  /** What `routes` calls it: the file without its extension, `"/users/[id]"`. */
  key: string;
  path: string;
  /** The holder it opens in, by key; none for the app's own stack. */
  in?: string;
  /** It holds a folder. */
  holder: boolean;
  page: boolean;
  parse: boolean;
};

type Folder = { dir: string; path: string; holder?: FileRoute; parent?: Folder };

const SOURCE = /\.(tsx|ts|jsx|js)$/;

/** The app's file routes. Throws on files that don't make an app. */
export function scanRoutes(appDir: string): FileRoute[] {
  const errors: string[] = [];
  const all: FileRoute[] = [];
  const target = new Map<FileRoute, string>();
  const folderOf = new Map<FileRoute, Folder>();

  function folder(f: Folder) {
    const entries = readdirSync(join(appDir, f.dir)).sort();
    const subs: [string, string][] = [];
    const files: FileRoute[] = [];
    for (const entry of entries) {
      const rel = f.dir ? `${f.dir}/${entry}` : entry;
      if (entry.startsWith(".") || entry.startsWith("_")) continue;
      if (statSync(join(appDir, rel)).isDirectory()) {
        subs.push([entry, rel]);
        continue;
      }
      if (!SOURCE.test(entry) || /\.d\.ts$|\.test\.|\.spec\./.test(entry)) continue;
      const [base, at] = entry.replace(SOURCE, "").split("@", 2) as [string, string?];
      const source = readFileSync(join(appDir, rel), "utf8");
      if (!/export\s+default\b|export\s*\{[^}]*\bas\s+default\b/.test(source)) {
        errors.push(`${rel}: no default export (the page's component)`);
      }
      const r: FileRoute = {
        file: rel,
        key: "/" + rel.replace(SOURCE, ""),
        path: base === "index" ? f.path : join2(f.path, segment(base, rel)),
        holder: false,
        page: exportsName(source, "page"),
        parse: exportsName(source, "parse"),
      };
      if (at !== undefined) target.set(r, at);
      folderOf.set(r, f);
      files.push(r);
      all.push(r);
    }
    for (const [name, rel] of subs) {
      const sub: Folder = { dir: rel, path: join2(f.path, segment(name, rel)), parent: f };
      // `x.tsx` next to `x/` with an index holds it.
      const holder = files.find((r) => r.file.split("/").pop()!.replace(SOURCE, "").split("@")[0] === name);
      const hasIndex = readdirSync(join(appDir, rel)).some((e) => SOURCE.test(e) && e.replace(SOURCE, "").split("@")[0] === "index");
      if (holder && hasIndex) {
        holder.holder = true;
        sub.holder = holder;
      }
      folder(sub);
    }
  }

  function segment(name: string, rel: string): string {
    if (/^\(.+\)$/.test(name)) return "";
    const param = /^\[(.+)\]$/.exec(name);
    if (!param) return name;
    if (param[1].startsWith("...")) errors.push(`${rel}: catch-all params ([...x]) aren't supported`);
    return `:${param[1]}`;
  }

  folder({ dir: "", path: "/" });

  // A page opens in its folder's holder, or the next one up.
  for (const r of all) {
    const at = target.get(r);
    if (at !== undefined) {
      if (at === "app") continue;
      const named = all.filter((h) => h.holder && h.file.split("/").pop()!.replace(SOURCE, "").split("@")[0] === at);
      if (named.length === 1) r.in = named[0]!.key;
      else if (named.length === 0) errors.push(`${r.file}: @${at} names no page that holds a folder (x.tsx next to x/ with an index.tsx)`);
      else errors.push(`${r.file}: @${at} could be ${named.map((h) => h.file).join(" or ")}`);
      continue;
    }
    for (let f: Folder | undefined = folderOf.get(r); f; f = f.parent) {
      if (f.holder && f.holder !== r) {
        r.in = f.holder.key;
        break;
      }
    }
  }

  // One page per address; a holder shares its address with its first page.
  const byPath = new Map<string, FileRoute[]>();
  for (const r of all) byPath.set(r.path, [...(byPath.get(r.path) ?? []), r]);
  for (const [path, rs] of byPath) {
    const own = rs.filter((r) => !rs.some((h) => h.holder && r.in === h.key));
    if (own.length > 1) errors.push(`${rs.map((r) => r.file).join(", ")}: all at ${path}`);
  }
  if (!all.some((r) => r.path === "/" && !r.in)) errors.push("no page at /: add index.tsx");

  if (errors.length) throw new Error(`[Fuse] file routes in ${appDir}:\n  ${errors.join("\n  ")}`);
  return all;
}

function join2(a: string, b: string): string {
  return "/" + [...a.split("/"), ...b.split("/")].filter(Boolean).join("/");
}

function exportsName(source: string, name: string): boolean {
  return (
    new RegExp(`export\\s+(?:const|let|var|function)\\s+${name}\\b`).test(source) ||
    new RegExp(`export\\s*\\{[^}]*\\b${name}\\b[^}]*\\}`).test(source)
  );
}

/** A path's addresses, as a TypeScript type: `/users/:id` is `` `/users/${string}` ``. */
function addressType(path: string): string {
  if (!path.includes(":")) return JSON.stringify(path);
  return "`" + path.replace(/:[^/]+/g, "${string}") + "`";
}

/**
 * `<gen>/routes.tsx` for [routes], importing the files from [importOf].
 * [app] is `src/app.tsx`'s import, when there is one.
 */
export function emitRoutes(routes: FileRoute[], importOf: (file: string) => string, app?: string): string {
  const byKey = new Map(routes.map((r) => [r.key, r]));
  const names = new Map(routes.map((r, i) => [r.key, `r${i}`]));
  const out: string[] = [];
  const done = new Set<string>();
  // Holders before the pages in them.
  const emit = (r: FileRoute) => {
    if (done.has(r.key)) return;
    done.add(r.key);
    if (r.in) emit(byKey.get(r.in)!);
    const m = `m${names.get(r.key)!.slice(1)}`;
    const opts = [`path: ${JSON.stringify(r.path)}`];
    if (r.in) opts.push(`in: ${names.get(r.in)}`);
    if (r.page) opts.push(`page: ${m}.page`);
    if (r.parse) opts.push(`parse: ${m}.parse`);
    opts.push(`component: ${m}.default`);
    out.push(`const ${names.get(r.key)} = route({ ${opts.join(", ")} });`);
  };
  routes.forEach(emit);
  const addresses = [...new Set(routes.map((r) => addressType(r.path)))];
  return [
    ROUTES_HEADER,
    'import { Navigator, route } from "solid-fuse";',
    ...(app ? [`import App from ${JSON.stringify(app)};`] : []),
    ...routes.map((r) => `import * as m${names.get(r.key)!.slice(1)} from ${JSON.stringify(importOf(r.file))};`),
    "",
    ...out,
    "",
    '/** The app\'s pages, by file: `routes["/users/[id]"]`. */',
    "export const routes = {",
    ...routes.map((r) => `  ${JSON.stringify(r.key)}: ${names.get(r.key)},`),
    "};",
    "",
    app
      ? "/** The app: `src/app.tsx`, which draws the app's own stack. */"
      : "/** The app: its own stack, starting at `/`. Add `src/app.tsx` to put something around it. */",
    "export function FileRoutes() {",
    app ? "  return <App />;" : "  return <Navigator />;",
    "}",
    "",
    `type Addresses = ${addresses.join(" | ")};`,
    "",
    'declare module "solid-fuse" {',
    "  interface Register {",
    "    address: Addresses | `${Addresses}?${string}`;",
    "  }",
    "}",
    "",
  ].join("\n");
}

export type RoutesResult = { written: boolean; count: number } | null;

/**
 * Writes `<genDir>/routes.tsx` from `<projectRoot>/src/app`, when it changed.
 * No app folder: removes a routes file this wrote, and gives null.
 */
export function writeRoutes(projectRoot: string, genDir: string): RoutesResult {
  const appDir = join(projectRoot, "src", "app");
  const out = join(genDir, "routes.tsx");
  if (!existsSync(appDir)) {
    if (existsSync(out) && readFileSync(out, "utf8").startsWith(ROUTES_HEADER)) unlinkSync(out);
    return null;
  }
  const routes = scanRoutes(appDir);
  const importOf = (abs: string) => {
    const spec = relative(genDir, abs).replace(/\\/g, "/").replace(SOURCE, "");
    return spec.startsWith(".") ? spec : `./${spec}`;
  };
  const appFile = ["tsx", "jsx", "ts", "js"].map((x) => join(projectRoot, "src", `app.${x}`)).find(existsSync);
  const code = emitRoutes(routes, (file) => importOf(join(appDir, file)), appFile && importOf(appFile));
  if (existsSync(out) && readFileSync(out, "utf8") === code) return { written: false, count: routes.length };
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, code);
  return { written: true, count: routes.length };
}

/** Generates the file routes when the build or dev server starts, and in dev again when `src/app` changes. */
export function fuseRoutesPlugin(o: { projectRoot: string; genDir: string }): Plugin {
  const appDir = join(o.projectRoot, "src", "app");
  let building = false;
  const generate = (why: string) => {
    try {
      const r = writeRoutes(o.projectRoot, o.genDir);
      if (r?.written && !building) console.log(`fuse routes (${why}): ${r.count} pages`);
    } catch (err) {
      // In dev the last good routes stay.
      if (building) throw err;
      console.error(err instanceof Error ? err.message : err);
    }
  };
  return {
    name: "solid-fuse:routes",
    enforce: "pre",
    configResolved(config) {
      building = config.command === "build";
    },
    buildStart() {
      if (building) generate("build");
    },
    configureServer(server) {
      generate("start");
      const appFile = join(o.projectRoot, "src", "app");
      server.watcher.add([appDir, ...["tsx", "jsx", "ts", "js"].map((x) => `${appFile}.${x}`)]);
      let timer: ReturnType<typeof setTimeout> | null = null;
      const changed = (file: string) => {
        if (relative(appDir, file).startsWith("..") && file.replace(SOURCE, "") !== appFile) return;
        if (timer) clearTimeout(timer);
        timer = setTimeout(() => generate("src/app changed"), 50);
      };
      server.watcher.on("add", changed);
      server.watcher.on("unlink", changed);
      server.watcher.on("change", changed);
      server.watcher.on("addDir", changed);
      server.watcher.on("unlinkDir", changed);
    },
  };
}
