/**
 * File routes: every file in `src/app/` becomes a `route()`, written to
 * `<gen>/routes.tsx` (imported as `#fuse/routes`). Only codegen: what the
 * files say is what a hand-written `route()` would say.
 *
 * - A file is a screen; `index` takes its folder's path. `[id]` is a param,
 *   `(group)` folders are left out of the path. Names starting with `_`
 *   (other than `_layout`) are left out, for helpers.
 * - A folder with a `_layout` is a layout: its files push inside it, and its
 *   default export gets that navigator as `children`. `export const tabs =
 *   ["feed", "profile"]` makes it a tabs layout: those children (a file, or
 *   a folder's index) are the tabs, in order.
 * - Parents: a file's parent is its folder's layout, else its folder's
 *   index, else the parent folder's, and so on. So a link opens what sits
 *   above it in the tree, and a push goes where that is.
 * - A file can `export const page` (its page type) and `export const parse`
 *   (its params from a link), as `route()` takes them.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync } from "fs";
import { dirname, join, relative } from "path";
import type { Plugin } from "vite";

export const ROUTES_HEADER = "// GENERATED by fuse from src/app/ (file routes). Do not edit.";

export type FileRoute = {
  /** The file, relative to the app folder: `users/[id].tsx`. */
  file: string;
  /** What `routes` calls it: the file without its extension, `index` dropped. */
  key: string;
  /** None for a group's stack layout with no index: it can't be linked to, only through. */
  path?: string;
  layout: boolean;
  /** A tabs layout's tabs, by key. */
  tabs?: string[];
  tab?: boolean;
  parent?: string;
  page: boolean;
  parse: boolean;
};

type Folder = {
  dir: string;
  path: string;
  group: boolean;
  layout?: FileRoute;
  index?: FileRoute;
  files: FileRoute[];
  folders: Map<string, Folder>;
  parent?: Folder;
};

const SOURCE = /\.(tsx|ts|jsx|js)$/;

/** The app's file routes, parents worked out. Throws on files that don't make an app. */
export function scanRoutes(appDir: string): FileRoute[] {
  const errors: string[] = [];
  const all: FileRoute[] = [];

  function folder(dir: string, path: string, parent?: Folder): Folder {
    const name = dir.split("/").pop() ?? "";
    const f: Folder = { dir, path, group: /^\(.+\)$/.test(name), files: [], folders: new Map(), parent };
    for (const entry of readdirSync(join(appDir, dir)).sort()) {
      const rel = dir ? `${dir}/${entry}` : entry;
      if (entry.startsWith(".") || (entry.startsWith("_") && !entry.startsWith("_layout."))) continue;
      if (statSync(join(appDir, rel)).isDirectory()) {
        f.folders.set(entry, folder(rel, join2(path, segment(entry, rel)), f));
        continue;
      }
      if (!SOURCE.test(entry) || /\.d\.ts$|\.test\.|\.spec\./.test(entry)) continue;
      const base = entry.replace(SOURCE, "");
      const source = readFileSync(join(appDir, rel), "utf8");
      if (!/export\s+default\b|export\s*\{[^}]*\bas\s+default\b/.test(source)) {
        errors.push(`${rel}: no default export (the screen's component)`);
      }
      const r: FileRoute = {
        file: rel,
        key: keyOf(rel),
        path: base === "index" || base === "_layout" ? path : join2(path, segment(base, rel)),
        layout: base === "_layout",
        page: exportsName(source, "page"),
        parse: exportsName(source, "parse"),
      };
      if (r.layout) {
        const tabs = tabNames(source, rel, errors);
        if (tabs) r.tabs = tabs;
        f.layout = r;
      } else if (base === "index") f.index = r;
      else f.files.push(r);
      all.push(r);
    }
    // `users/[id].tsx` next to `users/[id]/` is that folder's index.
    for (const [name, sub] of f.folders) {
      const i = f.files.findIndex((r) => r.file.split("/").pop()!.replace(SOURCE, "") === name);
      if (i < 0 || sub.index || sub.layout) continue;
      sub.index = f.files[i];
      f.files.splice(i, 1);
    }
    return f;
  }

  function segment(name: string, rel: string): string {
    if (/^\(.+\)$/.test(name)) return "";
    const param = /^\[(.+)\]$/.exec(name);
    if (!param) return name;
    if (param[1].startsWith("...")) errors.push(`${rel}: catch-all params ([...x]) aren't supported`);
    return `:${param[1]}`;
  }

  const root = folder("", "/");

  // A group's layout has its folder's path only when it is what opens
  // there: tabs, or a stack with an index. Else (auth screens around a
  // shared layout) it's only what its routes sit in.
  const groups = (f: Folder) => {
    if (f.group && f.layout && !f.layout.tabs && !f.index) f.layout.path = undefined;
    f.folders.forEach(groups);
  };
  groups(root);

  // Tabs: the names a tabs layout lists, in order.
  const visit = (f: Folder, fn: (f: Folder) => void) => {
    fn(f);
    for (const c of f.folders.values()) visit(c, fn);
  };
  visit(root, (f) => {
    if (!f.layout?.tabs) return;
    const names = f.layout.tabs;
    f.layout.tabs = [];
    if (f.index) errors.push(`${f.index.file}: a tabs layout has no index; its first tab opens at its path`);
    for (const name of names) {
      const file = f.files.find((r) => r.file.split("/").pop()!.replace(SOURCE, "") === name);
      const sub = f.folders.get(name);
      const t = file ?? sub?.layout ?? sub?.index;
      if (!t) {
        errors.push(`${f.layout.file}: tab "${name}" is neither a file nor a folder with an index or _layout`);
        continue;
      }
      t.tab = true;
      f.layout.tabs.push(t.key);
    }
  });

  // What a file in [f] has as parent: the folder's layout, else the route at
  // the folder's path (its index, or a group's), else the parent folder's.
  function ownerOf(f: Folder | undefined, self: FileRoute): FileRoute | undefined {
    if (!f) return undefined;
    if (f.layout && f.layout !== self) return f.layout;
    const here = atPath(f, f.path, self);
    return here ?? ownerOf(f.parent, self);
  }
  function atPath(f: Folder, path: string, self: FileRoute): FileRoute | undefined {
    if (f.index && f.index !== self && f.index.path === path) return f.index;
    for (const g of f.folders.values()) {
      if (!g.group) continue;
      if (g.layout) {
        if (g.layout !== self && g.layout.path === path) return g.layout;
        continue;
      }
      const r = atPath(g, path, self);
      if (r) return r;
    }
    return undefined;
  }

  visit(root, (f) => {
    const set = (r: FileRoute, p: FileRoute | undefined) => {
      if (!r.tab && p) r.parent = p.key;
    };
    if (f.layout) set(f.layout, ownerOf(f.parent, f.layout));
    if (f.index) set(f.index, f.layout ?? ownerOf(f.parent, f.index));
    for (const r of f.files) set(r, ownerOf(f, r));
  });

  // One route per link, but a stack layout shares its path with its index.
  const byPath = new Map<string, FileRoute[]>();
  for (const r of all) if (r.path !== undefined) byPath.set(r.path, [...(byPath.get(r.path) ?? []), r]);
  for (const [path, rs] of byPath) {
    const shared = rs.filter((r) => !(r.parent && rs.some((l) => l.layout && !l.tabs && l.key === r.parent)));
    if (shared.length > 1) errors.push(`${rs.map((r) => r.file).join(", ")}: all at ${path}`);
  }
  if (!all.some((r) => r.path === "/" && !r.parent)) errors.push("no route at /: add index.tsx");

  if (errors.length) throw new Error(`[Fuse] file routes in ${appDir}:\n  ${errors.join("\n  ")}`);
  return all;
}

function join2(a: string, b: string): string {
  return "/" + [...a.split("/"), ...b.split("/")].filter(Boolean).join("/");
}

function keyOf(rel: string): string {
  const parts = rel.replace(SOURCE, "").split("/");
  if (parts.at(-1) === "index") parts.pop();
  return "/" + parts.join("/");
}

function exportsName(source: string, name: string): boolean {
  return (
    new RegExp(`export\\s+(?:const|let|var|function)\\s+${name}\\b`).test(source) ||
    new RegExp(`export\\s*\\{[^}]*\\b${name}\\b[^}]*\\}`).test(source)
  );
}

function tabNames(source: string, rel: string, errors: string[]): string[] | undefined {
  if (!exportsName(source, "tabs")) return undefined;
  const m = /export\s+const\s+tabs\s*(?::[^=]+)?=\s*\[([^\]]*)\]/.exec(source);
  if (!m) {
    errors.push(`${rel}: write tabs as a list of names: export const tabs = ["feed", "profile"]`);
    return [];
  }
  return [...m[1].matchAll(/["'`]([^"'`]+)["'`]/g)].map((x) => x[1]);
}

/** A path's links, as a TypeScript type: `/users/:id` is `` `/users/${string}` ``. */
function linkType(path: string): string {
  if (!path.includes(":")) return JSON.stringify(path);
  return "`" + path.replace(/:[^/]+/g, "${string}") + "`";
}

/** `<gen>/routes.tsx` for [routes], importing the files from [importOf]. */
export function emitRoutes(routes: FileRoute[], importOf: (file: string) => string): string {
  const byKey = new Map(routes.map((r) => [r.key, r]));
  const names = new Map(routes.map((r, i) => [r.key, `r${i}`]));
  const out: string[] = [];
  const done = new Set<string>();
  // Parents and tabs before the routes that name them.
  const emit = (r: FileRoute) => {
    if (done.has(r.key)) return;
    done.add(r.key);
    if (r.parent) emit(byKey.get(r.parent)!);
    for (const t of r.tabs ?? []) emit(byKey.get(t)!);
    const m = `m${names.get(r.key)!.slice(1)}`;
    const opts = [r.path === undefined ? `name: ${JSON.stringify(r.key)}` : `path: ${JSON.stringify(r.path)}`];
    if (r.parent) opts.push(`parent: ${names.get(r.parent)}`);
    if (r.layout) opts.push(`navigator: ${r.tabs ? `tabs(${r.tabs.map((t) => names.get(t)).join(", ")})` : '"stack"'}`);
    if (r.page) opts.push(`page: ${m}.page`);
    if (r.parse) opts.push(`parse: ${m}.parse`);
    opts.push(`component: ${m}.default`);
    out.push(`const ${names.get(r.key)} = route({ ${opts.join(", ")} });`);
  };
  routes.forEach(emit);
  const root = routes.find((r) => r.path === "/" && !r.parent)!;
  const links = [...new Set(routes.flatMap((r) => (r.path !== undefined && (!r.layout || r.tabs) ? [linkType(r.path)] : [])))];
  return [
    ROUTES_HEADER,
    'import { Navigator, route, tabs } from "solid-fuse";',
    ...routes.map((r) => `import * as m${names.get(r.key)!.slice(1)} from ${JSON.stringify(importOf(r.file))};`),
    "",
    ...out,
    "",
    "/** The app's routes, by file: `routes[\"/users/[id]\"]`. */",
    "export const routes = {",
    ...routes.map((r) => `  ${JSON.stringify(r.key)}: ${names.get(r.key)},`),
    "};",
    "",
    "/** The app's navigator: it opens on the route at `/`. */",
    'export function Routes(props: Omit<Parameters<typeof Navigator>[0], "initialPage" | "controller">) {',
    `  return <Navigator initialPage={${names.get(root.key)}} {...props} />;`,
    "}",
    "",
    `type Links = ${links.join(" | ")};`,
    "",
    'declare module "solid-fuse" {',
    "  interface Register {",
    "    link: Links | `${Links}?${string}`;",
    "  }",
    "}",
    "",
  ].join("\n");
}

export type RoutesResult = { written: boolean; count: number } | null;

/**
 * Writes `<genDir>/routes.tsx` from `<projectRoot>/src/app`, when it changed.
 * No app folder: removes a routes file this wrote, and gives null.
 */
export function writeRoutes(projectRoot: string, genDir: string): RoutesResult {
  const appDir = join(projectRoot, "src", "app");
  const out = join(genDir, "routes.tsx");
  if (!existsSync(appDir)) {
    if (existsSync(out) && readFileSync(out, "utf8").startsWith(ROUTES_HEADER)) unlinkSync(out);
    return null;
  }
  const routes = scanRoutes(appDir);
  const code = emitRoutes(routes, (file) => {
    const spec = relative(genDir, join(appDir, file)).replace(/\\/g, "/").replace(SOURCE, "");
    return spec.startsWith(".") ? spec : `./${spec}`;
  });
  if (existsSync(out) && readFileSync(out, "utf8") === code) return { written: false, count: routes.length };
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, code);
  return { written: true, count: routes.length };
}

/** Generates the file routes when the build or dev server starts, and in dev again when `src/app` changes. */
export function fuseRoutesPlugin(o: { projectRoot: string; genDir: string }): Plugin {
  const appDir = join(o.projectRoot, "src", "app");
  let building = false;
  const generate = (why: string) => {
    try {
      const r = writeRoutes(o.projectRoot, o.genDir);
      if (r?.written && !building) console.log(`fuse routes (${why}): ${r.count} routes`);
    } catch (err) {
      // In dev the last good routes stay.
      if (building) throw err;
      console.error(err instanceof Error ? err.message : err);
    }
  };
  return {
    name: "solid-fuse:routes",
    enforce: "pre",
    configResolved(config) {
      building = config.command === "build";
    },
    buildStart() {
      if (building) generate("build");
    },
    configureServer(server) {
      generate("start");
      server.watcher.add(appDir);
      let timer: ReturnType<typeof setTimeout> | null = null;
      const changed = (file: string) => {
        if (relative(appDir, file).startsWith("..")) return;
        if (timer) clearTimeout(timer);
        timer = setTimeout(() => generate("src/app changed"), 50);
      };
      server.watcher.on("add", changed);
      server.watcher.on("unlink", changed);
      server.watcher.on("change", changed);
      server.watcher.on("addDir", changed);
      server.watcher.on("unlinkDir", changed);
    },
  };
}
